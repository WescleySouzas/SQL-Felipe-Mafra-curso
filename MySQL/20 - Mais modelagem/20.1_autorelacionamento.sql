/* NOME, VALOR, HORAS  E O NOME DO PRE REQUISITO DO CURSO */

SELECT C.NOME AS CURSO,C.VALOR AS VALOR, C.HORAS AS CARGA, IFNULL(P.NOME, "----") AS PREREQ
FROM  CURSOS C 
LEFT JOIN CURSOS P
ON P.IDCURSO = C.ID_PREREQ;